SCALES = {s["code"]: s for s in (PHQ9, GAD7, CSSRS)}


def score_answers(code: str, answers: List[int]) -> Dict[str, Any]:
    """Подсчёт: сумма пунктов + градация по КР МЗ + жёсткие флаги безопасности."""
    scale = SCALES[code]
    if len(answers) != len(scale["items"]):
        return {"error": f"ожидалось {len(scale['items'])} ответов, получено {len(answers)}"}
    total = sum(int(a) for a in answers)
    sev = next(s for s in scale["severity"] if total <= s["max"])
    out: Dict[str, Any] = {
        "scale_code": code, "total_score": total,
        "severity": sev["label"], "items": answers,
    }
    if code == "PHQ-9":
        out["item9_suicidal"] = answers[8]
        out["suicide_flag"] = answers[8] >= 1
    if code == "C-SSRS-SCREEN":
        out["items_456_positive"] = any(a >= 1 for a in answers[3:6])
        out["suicide_flag"] = out["items_456_positive"] or total >= 2
    return out
