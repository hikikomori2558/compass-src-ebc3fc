SCALES = {s["code"]: s for s in (PHQ9, GAD7, HADS, HAMA, CGI, CSSRS)}


def _sev(scale: Dict[str, Any], total: int) -> str:
    return next(s["label"] for s in scale["severity"] if total <= s["max"])


def score_answers(code: str, answers: List[int]) -> Dict[str, Any]:
    """Подсчёт: сумма пунктов + градация по КР МЗ + жёсткие флаги безопасности.
    HADS/HAM-A дополнительно возвращают подшкалы; weights HADS уже зашиты в бланк."""
    scale = SCALES[code]
    if len(answers) != len(scale["items"]):
        return {"error": f"ожидалось {len(scale['items'])} ответов, получено {len(answers)}"}
    total = sum(int(a) for a in answers)
    out: Dict[str, Any] = {
        "scale_code": code, "total_score": total,
        "items": answers,
    }
    if scale.get("severity"):
        out["severity"] = _sev(scale, total)
    if code == "HADS":
        a_idx, d_idx = scale["subscales"]["A"], scale["subscales"]["D"]
        a_total = sum(int(answers[i]) for i in a_idx)
        d_total = sum(int(answers[i]) for i in d_idx)
        out["hads_a"] = a_total
        out["hads_d"] = d_total
        out["hads_a_band"] = ("норма (0–7)" if a_total <= 7 else
                              "субклинически (8–10)" if a_total <= 10 else
                              "клинически значимо (≥11)")
        out["hads_d_band"] = ("норма (0–7)" if d_total <= 7 else
                              "субклинически (8–10)" if d_total <= 10 else
                              "клинически значимо (≥11)")
        out["flag"] = a_total >= 11 or d_total >= 11
    if code == "HAM-A":
        psy = sum(int(answers[i]) for i in scale["subscales"]["psychic"])
        som = sum(int(answers[i]) for i in scale["subscales"]["somatic"])
        out["hama_psychic"] = psy
        out["hama_somatic"] = som
        out["reduction_note"] = "ответ = редукция ≥50% от исходного; ремиссия ≤7 (КР ГТР)"
    if code == "PHQ-9":
        out["item9_suicidal"] = answers[8]
        out["suicide_flag"] = answers[8] >= 1
    if code == "C-SSRS-SCREEN":
        out["items_456_positive"] = any(a >= 1 for a in answers[3:6])
        out["suicide_flag"] = out["items_456_positive"] or total >= 2
    return out
