def guidance_for(codes: List[str]) -> List[Dict[str, Any]]:
    """Карточки пояснений для отмеченных кодов (в момент возникновения)."""
    out: List[Dict[str, Any]] = []
    for code in codes:
        g = GUIDANCE.get(code)
        if g:
            out.append({"code": code, **g})
    return out
